const Lang = {
  KEY: 'aw_lang',
  DEFAULT: 'fr',
  SUPPORTED: ['fr', 'ar', 'en'],
  LABELS: { fr: 'FR', ar: 'AR', en: 'EN' },

  get() {
    const saved = localStorage.getItem(this.KEY);
    return this.SUPPORTED.includes(saved) ? saved : this.DEFAULT;
  },
  set(lang) {
    if (!this.SUPPORTED.includes(lang)) return;
    localStorage.setItem(this.KEY, lang);
    window.location.reload();
  },
  dir(lang) {
    return lang === 'ar' ? 'rtl' : 'ltr';
  },
};

// Traduction d'une clé pour la langue courante (repli sur le français puis sur la clé elle-même)
function t(key) {
  const lang = Lang.get();
  return (I18N[lang] && I18N[lang][key]) || I18N.fr[key] || key;
}

// Applique les traductions à tout le DOM déjà présent dans la page
// (à appeler après tout rendu dynamique — navbar, footer, sidebar…)
function applyI18n(root = document) {
  const lang = Lang.get();
  document.documentElement.setAttribute('lang', lang);
  document.documentElement.setAttribute('dir', Lang.dir(lang));
  root.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  root.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = t(el.getAttribute('data-i18n-html'));
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
  });
}

// Petit sélecteur de langue (3 boutons) à injecter dans la navbar / sidebar
function langSwitcherHTML(extraClass = '') {
  const current = Lang.get();
  return `<div class="aw-lang-switch ${extraClass}">
    ${Lang.SUPPORTED.map(l => `<button type="button" class="aw-lang-btn ${l === current ? 'active' : ''}" onclick="Lang.set('${l}')">${Lang.LABELS[l]}</button>`).join('')}
  </div>`;
}

document.addEventListener('DOMContentLoaded', () => applyI18n());
